/*
Напишіть функцію celsiusToFahrenheit(),
яка приймає температуру в градусах Цельсія і конвертує її в градуси Фаренгейта і потім пвертає результат у вигляді числа.
*/

export default celsiusToFahrenheit; // Не видаляти цей рядок

function celsiusToFahrenheit(celsius) {
    return (celsius * 9/5) + 32;
}
